import { mkdir, writeFile } from 'node:fs/promises';
import { basename, join } from 'node:path';

const fileKey = process.env.FIGMA_FILE_KEY ?? 'CSe45kCpGg8PHrJarkfgKt';
const token = process.env.FIGMA_ACCESS_TOKEN;
const dryRun = process.argv.includes('--dry-run');
const apiBase = 'https://api.figma.com/v1';
const outputDir = join(process.cwd(), 'src', 'assets', 'figma');
const registryPath = join(outputDir, 'registry.ts');

if (!token && !dryRun) {
  console.error('FIGMA_ACCESS_TOKEN is required.');
  process.exit(1);
}

async function figmaFetch(path) {
  const response = await fetch(`${apiBase}${path}`, {
    headers: token ? { 'X-Figma-Token': token } : {},
  });
  if (!response.ok) {
    throw new Error(`Figma API ${response.status}: ${await response.text()}`);
  }
  return response.json();
}

function safeName(name, nodeId) {
  const slug = name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  return `${slug || 'component'}-${nodeId.replace(':', '-')}`;
}

async function main() {
  if (dryRun) {
    console.log(`Would sync published assets for ${fileKey} into src/assets/figma`);
    console.log('Exports are requested as SVG in batches of 100 nodes.');
    return;
  }

  const { meta = [] } = await figmaFetch(`/files/${fileKey}/components`);
  const components = meta.filter((component) => component.node_id && component.name);
  await mkdir(outputDir, { recursive: true });
  const registry = {};

  for (let index = 0; index < components.length; index += 100) {
    const batch = components.slice(index, index + 100);
    const ids = batch.map((component) => component.node_id).join(',');
    const images = await figmaFetch(`/images/${fileKey}?ids=${encodeURIComponent(ids)}&format=svg&use_absolute_bounds=true`);
    for (const component of batch) {
      const url = images.images?.[component.node_id];
      if (!url) continue;
      const assetName = `${safeName(component.name, component.node_id)}.svg`;
      const assetPath = join(outputDir, assetName);
      const asset = await fetch(url);
      if (!asset.ok) throw new Error(`Asset download ${asset.status}: ${url}`);
      await writeFile(assetPath, Buffer.from(await asset.arrayBuffer()));
      registry[component.node_id] = {
        name: component.name,
        nodeId: component.node_id,
        fileName: assetName,
        source: component.documentation?.description ?? null,
      };
    }
    console.log(`Synced ${Math.min(index + batch.length, components.length)}/${components.length}`);
  }

  const entries = Object.entries(registry).sort(([left], [right]) => left.localeCompare(right));
  const source = `// Generated by npm run sync:figma-assets. Do not edit.\nexport const figmaAssets = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;\n`;
  await writeFile(registryPath, source);
  console.log(`Wrote ${entries.length} assets and ${basename(registryPath)}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});